// 供回放引擎使用：把曲目音符序列转为事件列表（3 档力度起伏模拟弹奏起伏）
function songToEvents(song, baseVelocity = 80) {
  const events = [];
  let t = 0;
  const beatSec = 60 / song.bpm;
  song.notes.forEach(([midi, dur], i) => {
    if (midi > 0) {
      // 力度起伏：按音符位置 0/1/2 档 + 轻微随机
      const level = i % 3;
      const vel = Math.min(127, Math.round(baseVelocity + (level - 1) * 25 + (Math.random() * 8 - 4)));
      events.push({ a: 'down', n: midi, v: Math.max(30, vel), t: +(t * beatSec).toFixed(3) });
      events.push({ a: 'up', n: midi, t: +((t + Math.min(dur, 0.9)) * beatSec).toFixed(3) });
    }
    t += dur;
  });
  return events;
}

